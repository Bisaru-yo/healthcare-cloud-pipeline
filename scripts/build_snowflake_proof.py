"""Generate an isolated warehouse proof from the actual first-batch loader.

Run from the project directory. --check detects drift without writing files.
This creates SQL; it does not execute Snowflake operations.
"""
import argparse
import hashlib
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from pipeline.quality import fingerprint, read_and_validate

ROOT = Path(__file__).resolve().parents[1]


def build():
    loader = (ROOT / 'sql/03_snowflake_load.sql').read_text()
    data, _ = read_and_validate(ROOT / 'data/source')
    original = min(data['encounters'], key=lambda row: row['id'])
    corrected = dict(original)
    corrected['total_claim_cost_cents'] += 100
    fixture_id = original['id']
    corrected_hash = fingerprint(corrected)
    claim_sum = sum(row['total_claim_cost_cents'] for row in data['encounters']) + 100
    coverage_sum = sum(row['payer_coverage_cents'] for row in data['encounters'])
    body = loader.split('EXECUTE IMMEDIATE $$\n', 1)[1].rsplit('\n$$;', 1)[0]
    # Fully qualify every persistent target, including the audit, in the QA copy.
    body = re.sub(r'\b(PATIENTS|PAYERS|ENCOUNTERS|LOAD_RUNS)\b', r'HEALTHCARE.QA.\1', body)
    body = body.replace('@HEALTHCARE_S3_STAGE/', '@HEALTHCARE.RAW.HEALTHCARE_S3_STAGE/')
    body = body.replace("FORMAT_NAME = 'HEALTHCARE_JSON'", "FORMAT_NAME = 'HEALTHCARE.RAW.HEALTHCARE_JSON'")
    body = body.replace('    result_rows RESULTSET;', "    qa_rollback_error EXCEPTION (-20005, 'Deliberate failure after all merges; verify rollback.');\n    result_rows RESULTSET;")
    injection = f'''
    -- TEST-ONLY injection after reading the genuine S3 batch. No S3 writes.
    IF (test_scenario IN ('late_correction', 'force_rollback')) THEN
        UPDATE BATCH_ENCOUNTERS
        SET total_claim_cost_cents = TO_VARCHAR(TO_NUMBER(total_claim_cost_cents) + 100),
            row_hash = '{corrected_hash}'
        WHERE id = '{fixture_id}';
        UPDATE BATCH_MANIFEST SET payload = OBJECT_INSERT(payload, 'tables',
            OBJECT_INSERT(payload:tables::OBJECT, 'encounters',
                OBJECT_INSERT(payload:tables.encounters::OBJECT, 'amount_totals_cents',
                    OBJECT_CONSTRUCT('total_claim_cost_cents', {claim_sum},
                                     'payer_coverage_cents', {coverage_sum}), TRUE), TRUE), TRUE);
    ELSEIF (test_scenario = 'orphan') THEN
        UPDATE BATCH_ENCOUNTERS SET patient = '__qa_missing_patient__'
        WHERE id = '{fixture_id}';
    END IF;

'''
    anchor = '    INSERT INTO BATCH_CHECKS\n'
    assert body.count(anchor) == 1
    body = body.replace(anchor, injection + anchor)
    anchor = '    INSERT INTO HEALTHCARE.QA.LOAD_RUNS\n'
    assert body.count(anchor) == 1
    body = body.replace(anchor, "    IF (test_scenario = 'force_rollback') THEN\n        RAISE qa_rollback_error;\n    END IF;\n\n" + anchor)
    # Ensure all 3 merge statements are still the actual loader statements,
    # except for qualification of their isolated target names.
    for table in ('PATIENTS', 'PAYERS', 'ENCOUNTERS'):
        statement = loader.split('    MERGE INTO ' + table, 1)[1].split(';', 1)[0]
        assert ('    MERGE INTO HEALTHCARE.QA.' + table + statement + ';') in body
    prefix = '''-- Generated by scripts/build_snowflake_proof.py; do not hand-edit.
-- Warehouse-only fault injection using the real loader's gates and merges.
-- Read S3 and RAW; reset only the dedicated QA copies below.
USE ROLE ACCOUNTADMIN;
USE WAREHOUSE HEALTHCARE_WH;
USE DATABASE HEALTHCARE;
CREATE SCHEMA IF NOT EXISTS HEALTHCARE.QA;
USE SCHEMA HEALTHCARE.QA;
ALTER SESSION SET TIMEZONE = 'UTC';
ALTER SESSION SET ERROR_ON_NONDETERMINISTIC_MERGE = TRUE;
CREATE OR REPLACE TEMPORARY FILE FORMAT BATCH_CSV
    TYPE = CSV FIELD_DELIMITER = ',' SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"' ESCAPE_UNENCLOSED_FIELD = NONE
    EMPTY_FIELD_AS_NULL = FALSE NULL_IF = ()
    ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE ENCODING = 'UTF8';
'''
    prefix += '-- Derived from loader SHA-256: ' + hashlib.sha256(loader.encode()).hexdigest() + '\n'
    for table in ('PATIENTS', 'PAYERS', 'ENCOUNTERS'):
        prefix += f'CREATE OR REPLACE TABLE HEALTHCARE.QA.{table} CLONE HEALTHCARE.RAW.{table};\n'
        prefix += f'CREATE OR REPLACE TEMPORARY TABLE RAW_BEFORE_{table} AS SELECT * FROM HEALTHCARE.RAW.{table};\n'
    audit_ddl = loader.split('CREATE TABLE IF NOT EXISTS LOAD_RUNS (', 1)[1].split(');', 1)[0]
    prefix += 'CREATE TABLE IF NOT EXISTS HEALTHCARE.QA.LOAD_RUNS (' + audit_ddl + ');\n'
    prefix += '''CREATE TABLE IF NOT EXISTS HEALTHCARE.QA.PROOF_RESULTS (
    proof_id VARCHAR, scenario VARCHAR, status VARCHAR, details VARIANT,
    recorded_at TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);
CREATE OR REPLACE PROCEDURE HEALTHCARE.QA.LOAD_FIXTURE(test_scenario VARCHAR)
RETURNS TABLE()
LANGUAGE SQL
EXECUTE AS CALLER
AS $$
'''
    suffix = '''
-- The harness catches only the exact errors deliberately expected by each case.
-- All other errors stop the proof and prevent a final passed result table.
EXECUTE IMMEDIATE $$
DECLARE
    proof_key VARCHAR DEFAULT UUID_STRING();
    failures NUMBER DEFAULT 0;
    expected_seen BOOLEAN DEFAULT FALSE;
    bad_proof EXCEPTION (-20010, 'QA proof assertion failed; inspect QA audit and checks.');
    rows_out RESULTSET;
BEGIN
'''
    def assertion(query):
        # SELECT ... INTO needs a FROM-backed outer query in this context.
        # Preserve the scalar check as a named column of a one-row derived table.
        return (f'    SELECT check_value INTO :failures\n'
                f'    FROM (SELECT ({query}) AS check_value) AS assertion_result;\n'
                '    IF (failures IS NULL OR failures <> 0) THEN RAISE bad_proof; END IF;\n')
    def symmetric_diff(left, right, columns='*'):
        return f'(SELECT COUNT(*) FROM (SELECT {columns} FROM {left} MINUS SELECT {columns} FROM {right})) + (SELECT COUNT(*) FROM (SELECT {columns} FROM {right} MINUS SELECT {columns} FROM {left}))'
    def record(scenario, details):
        return f"    INSERT INTO HEALTHCARE.QA.PROOF_RESULTS (proof_id, scenario, status, details)\n    SELECT :proof_key, '{scenario}', 'passed', {details};\n"
    # First assert the fixture is the known original batch, then change one row.
    suffix += assertion(f"SELECT IFF(COUNT(*) = 1 AND MIN(total_claim_cost_cents) = {original['total_claim_cost_cents']} AND MIN(row_hash) = '{fingerprint(original)}', 0, 1) FROM HEALTHCARE.QA.ENCOUNTERS WHERE id = '{fixture_id}'")
    suffix += "    CALL HEALTHCARE.QA.LOAD_FIXTURE('late_correction');\n"
    suffix += assertion("SELECT COUNT(*) FROM BATCH_METRICS WHERE inserted <> 0 OR source_rows <> reconciled_rows OR (table_name = 'encounters' AND (updated <> 1 OR unchanged <> 53345 OR target_total_rows <> 53346)) OR (table_name <> 'encounters' AND updated <> 0)")
    suffix += assertion(f"SELECT IFF(COUNT(*) = 1 AND MIN(total_claim_cost_cents) = {corrected['total_claim_cost_cents']} AND MIN(row_hash) = '{corrected_hash}', 0, 1) FROM HEALTHCARE.QA.ENCOUNTERS WHERE id = '{fixture_id}'")
    # Exactly one key has changed projected content; all other fields stay equal.
    ec = ['id','start_at','stop_at','patient_id','payer_id','encounter_class','encounter_code','total_claim_cost_cents','payer_coverage_cents','row_hash']
    eq = ' AND '.join(f'EQUAL_NULL(t.{c}, b.{c})' for c in ec)
    suffix += assertion(f'SELECT ABS(COUNT(*) - 1) FROM HEALTHCARE.QA.ENCOUNTERS t JOIN RAW_BEFORE_ENCOUNTERS b ON t.id = b.id WHERE NOT ({eq})')
    suffix += record('late_correction', "OBJECT_CONSTRUCT('updated_encounters', 1, 'inserted_encounters', 0, 'cost_delta_cents', 100, 'encounter_id', '" + fixture_id + "')")
    # A clean reload restores the original business values through the same merge.
    suffix += "    CALL HEALTHCARE.QA.LOAD_FIXTURE('recovery');\n"
    suffix += assertion("SELECT COUNT(*) FROM BATCH_METRICS WHERE inserted <> 0 OR source_rows <> reconciled_rows OR (table_name = 'encounters' AND updated <> 1) OR (table_name <> 'encounters' AND updated <> 0)")
    for table in ('PATIENTS','PAYERS','ENCOUNTERS'):
        target_ddl = loader.split('CREATE TABLE IF NOT EXISTS ' + table + ' (', 1)[1].split(');',1)[0]
        names = [line.strip().split()[0] for line in target_ddl.splitlines() if line.strip()]
        cols = ', '.join(n for n in names if n != 'loaded_at')
        suffix += assertion(symmetric_diff('HEALTHCARE.QA.' + table, 'RAW_BEFORE_' + table, cols))
        suffix += f'    CREATE OR REPLACE TEMPORARY TABLE QA_BEFORE_{table} AS SELECT * FROM HEALTHCARE.QA.{table};\n'
    suffix += record('recovery', "OBJECT_CONSTRUCT('updated_encounters', 1, 'original_content_restored', TRUE)")
    for scenario, code, label in [('orphan',-20002,'orphan_rejection'),('force_rollback',-20005,'transaction_rollback')]:
        suffix += f'''    expected_seen := FALSE;
    BEGIN
        CALL HEALTHCARE.QA.LOAD_FIXTURE('{scenario}');
    EXCEPTION WHEN OTHER THEN
        IF (SQLCODE = {code}) THEN expected_seen := TRUE;
        ELSE RAISE;
        END IF;
    END;
    IF (NOT expected_seen) THEN RAISE bad_proof; END IF;
'''
        if scenario == 'orphan':
            suffix += assertion("SELECT IFF(COUNT(*) = 1 AND MIN(violations) = 1, 0, 1) FROM BATCH_CHECKS WHERE check_name = 'patient_foreign_keys'")
            suffix += assertion("SELECT COUNT(*) FROM BATCH_CHECKS WHERE check_name <> 'patient_foreign_keys' AND (violations IS NULL OR violations <> 0)")
        for table in ('PATIENTS','PAYERS','ENCOUNTERS'):
            suffix += assertion(symmetric_diff('HEALTHCARE.QA.' + table, 'QA_BEFORE_' + table))
        suffix += record(label, f"OBJECT_CONSTRUCT('expected_error_code', {code}, 'all_target_values_preserved', TRUE)")
    # Direct, bidirectional row comparisons include RAW lineage and timestamps.
    for table in ('PATIENTS','PAYERS','ENCOUNTERS'):
        suffix += assertion(symmetric_diff('HEALTHCARE.RAW.' + table, 'RAW_BEFORE_' + table))
    suffix += assertion('SELECT ABS(COUNT(*) - 4) FROM HEALTHCARE.QA.PROOF_RESULTS WHERE proof_id = :proof_key')
    suffix += '''    rows_out := (SELECT proof_id, scenario, status, details,
        TRUE AS raw_tables_unchanged
        FROM HEALTHCARE.QA.PROOF_RESULTS WHERE proof_id = :proof_key ORDER BY recorded_at);
    RETURN TABLE(rows_out);
END;
$$;
'''
    return prefix + body + '\n$$;\n' + suffix


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT / 'sql/04_snowflake_quality_proof.sql'
    text = build()
    if args.check:
        if not path.is_file() or path.read_text() != text:
            raise SystemExit('Proof SQL is stale; regenerate it with this script.')
        print('QA SQL matches the current loader and normalized source fixture.')
    else:
        path.write_text(text)
        print('Generated', path.name)


if __name__ == '__main__':
    main()
